// Chụp tab Kho: Hình / Icon / Âm thanh, chèn 1 hình + 1 âm thanh, kiểm lỗi trang
const {chromium} = require('playwright');
const M = '/home/claude/testmedia/';
(async () => {
  const w = +(process.argv[2] || 1440), h = +(process.argv[3] || 900);
  const mob = w < 900;
  const b = await chromium.launch();
  const p = await (await b.newContext({viewport: {width: w, height: h}, deviceScaleFactor: mob ? 2 : 1, hasTouch: mob, isMobile: mob})).newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(process.env.URL || 'http://localhost:8790/');
  await p.waitForTimeout(800);
  const fc = p.waitForEvent('filechooser');
  await p.click((await p.locator('#home').isVisible()) ? '#btnNew' : '.drop.main');
  await (await fc).setFiles(M + 'speech_mid_g30.mp4');
  await p.waitForFunction(() => window.__dv?.p?.main, null, {timeout: 60000});
  if (mob) await p.evaluate(() => document.querySelector('[data-act="project"]')?.click());
  await p.evaluate(() => document.querySelector('#side [data-tab="media"]').click());
  await p.waitForTimeout(300);
  await p.evaluate(() => document.querySelector('[data-libtab="emoji"]').click());
  await p.waitForTimeout(1200);
  await p.fill('#libQ', 'nhà');
  await p.waitForTimeout(900);
  await p.screenshot({path: `test/lib-${w}-emoji.png`});
  const n = await p.locator('.lib-it').count();
  await p.locator('.lib-it').first().click();
  await p.waitForTimeout(800);
  await p.evaluate(() => document.querySelector('#side [data-tab="media"]').click());
  await p.evaluate(() => document.querySelector('[data-libtab="icon"]').click());
  await p.waitForTimeout(1200);
  await p.screenshot({path: `test/lib-${w}-icon.png`});
  await p.evaluate(() => document.querySelector('[data-libtab="sfx"]').click());
  await p.waitForTimeout(300);
  await p.locator('[data-addsfx="cash"]').click();
  await p.waitForTimeout(600);
  await p.screenshot({path: `test/lib-${w}-sfx.png`});
  const st = await p.evaluate(() => ({stickers: window.__dv.p.stickers.map((s) => s.key + ':' + s.label), sfx: window.__dv.p.sfx.map((s) => s.sfx)}));
  console.log(JSON.stringify({w, found: n, ...st, errs}));
  await b.close();
})();
